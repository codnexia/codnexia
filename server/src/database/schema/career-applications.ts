// Career/job applications submitted from the public careers page
import { pgTable, uuid, varchar, text, timestamp, jsonb, index } from 'drizzle-orm/pg-core';

export const careerApplications = pgTable('career_applications', {
  id: uuid('id').defaultRandom().primaryKey(),
  firstName: varchar('first_name', { length: 255 }).notNull(),
  lastName: varchar('last_name', { length: 255 }).notNull(),
  email: varchar('email', { length: 255 }).notNull(),
  phone: varchar('phone', { length: 50 }).notNull(),
  countryCode: varchar('country_code', { length: 10 }),
  country: varchar('country', { length: 255 }).notNull(),
  city: varchar('city', { length: 255 }),
  nationality: varchar('nationality', { length: 255 }),
  linkedin: varchar('linkedin', { length: 500 }),
  github: varchar('github', { length: 500 }),
  portfolio: varchar('portfolio', { length: 500 }),
  website: varchar('website', { length: 500 }),
  currentRole: varchar('current_role', { length: 255 }).notNull(),
  company: varchar('company', { length: 255 }),
  experience: varchar('experience', { length: 100 }).notNull(),
  noticePeriod: varchar('notice_period', { length: 100 }),
  employmentType: varchar('employment_type', { length: 50 }).notNull(),
  workMode: varchar('work_mode', { length: 50 }).notNull(),
  salaryExpectation: varchar('salary_expectation', { length: 100 }),
  salaryCurrency: varchar('salary_currency', { length: 10 }),
  primaryStack: jsonb('primary_stack').$type<string[]>().default([]),
  otherSkills: text('other_skills'),
  proficiency: varchar('proficiency', { length: 100 }),
  languages: text('languages'),
  certifications: text('certifications'),
  degree: varchar('degree', { length: 255 }).notNull(),
  field: varchar('field', { length: 255 }),
  university: varchar('university', { length: 255 }),
  gradYear: varchar('grad_year', { length: 10 }),
  position: varchar('position', { length: 255 }).notNull(),
  coverLetter: text('cover_letter').notNull(),
  heardFrom: varchar('heard_from', { length: 255 }),
  availability: varchar('availability', { length: 100 }),
  callDate: varchar('call_date', { length: 20 }),
  callTime: varchar('call_time', { length: 20 }),
  timezone: varchar('timezone', { length: 50 }),
  callTopics: jsonb('call_topics').$type<string[]>().default([]),
  status: varchar('status', { length: 50 }).default('new').notNull(),
  createdAt: timestamp('created_at').defaultNow().notNull(),
}, (table) => [
  index('idx_career_apps_created_at').on(table.createdAt),
  index('idx_career_apps_status').on(table.status),
  index('idx_career_apps_position').on(table.position),
]);
